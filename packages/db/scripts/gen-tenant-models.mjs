#!/usr/bin/env node
// Emits src/tenant-models.generated.ts from the Prisma schema so the runtime
// scoping extension always knows exactly which models are tenant-owned.
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parseModels, tenantModels, RLS_EXEMPT } from "./schema-meta.mjs";
import { SHARED_CATALOG } from "./gen-rls.mjs";

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "tenant-models.generated.ts");
const models = tenantModels(parseModels()).filter((t) => !t.isRoot && !(t.name in RLS_EXEMPT));

const body = `// GENERATED by scripts/gen-tenant-models.mjs — do not edit.
// Models carrying an organizationId column, keyed by Prisma model name.

export const TENANT_MODELS: ReadonlySet<string> = new Set([
${models.map((m) => `  "${m.name}",`).join("\n")}
]);

/** Tenant models whose organizationId = NULL rows are a shared platform catalog. */
export const SHARED_CATALOG_MODELS: ReadonlySet<string> = new Set([
${[...SHARED_CATALOG].sort().map((n) => `  "${n}",`).join("\n")}
]);

/** The tenant root: scoped by its own id. */
export const TENANT_ROOT_MODEL = "Organization";
`;
writeFileSync(out, body);
console.log(`wrote ${models.length} tenant models → ${out}`);
